-- Advisory opinions, author-controlled medals; every fixture is rolled back.
begin;
do $$
declare
  a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); c uuid:=gen_random_uuid(); d uuid:=gen_random_uuid(); outsider uuid:=gen_random_uuid();
  g uuid; other_group uuid; r uuid:=gen_random_uuid(); other_r uuid:=gen_random_uuid(); comment_id uuid; invitation text;
  result jsonb; state jsonb; affected integer;
begin
  insert into auth.users(id,is_anonymous,raw_user_meta_data) values(a,false,'{}'),(b,false,'{}'),(c,false,'{}'),(d,false,'{}'),(outsider,false,'{}');
  perform set_config('request.jwt.claim.sub',a::text,true); perform set_config('role','authenticated',true);
  g:=public.create_catalog_group('의견 테스트','#5285bc'); invitation:=public.create_catalog_invite(g);
  other_group:=public.create_catalog_group('다른 그룹 보존','#b87981');
  insert into public.restaurants(id,group_id,created_by,name,category,rating,area,lat,lng) values(r,g,a,'같은 식당','한식',2,'서울',37.5,127),(other_r,other_group,a,'같은 식당','한식',1,'서울',37.5,127);
  insert into public.restaurant_photos(restaurant_id,storage_path,created_by,sort_order) values(r,r::text||'/test.jpg',a,0);
  insert into storage.objects(bucket_id,name) values('restaurant-photos',r::text||'/test.jpg');
  state:=public.restaurant_discussion(r);
  if (state->>'can_vote')::boolean then raise exception 'author counted as voter'; end if;
  begin perform public.cast_restaurant_vote(r,1,'up'); raise exception 'author allowed to vote'; exception when insufficient_privilege then null; end;
  perform set_config('request.jwt.claim.sub',b::text,true); perform public.join_catalog_group(invitation);
  perform set_config('request.jwt.claim.sub',c::text,true); perform public.join_catalog_group(invitation);
  perform set_config('request.jwt.claim.sub',d::text,true); perform public.join_catalog_group(invitation);
  insert into public.restaurant_comments(restaurant_id,user_id,body) values(r,d,'내 의견') returning id into comment_id;
  update public.restaurant_comments set body='수정한 의견' where id=comment_id;
  if (select body from public.restaurant_comments where id=comment_id)<>'수정한 의견' then raise exception 'own comment update failed'; end if;
  begin update public.restaurant_comments set user_id=b where id=comment_id; raise exception 'comment reassignment allowed'; exception when insufficient_privilege then null; end;
  perform public.cast_restaurant_vote(r,1,'up');
  perform set_config('request.jwt.claim.sub',b::text,true);
  update public.restaurant_comments set body='다른 회원 수정' where id=comment_id; get diagnostics affected=row_count;
  if affected<>0 then raise exception 'nonowner edited comment'; end if;
  delete from public.restaurant_comments where id=comment_id; get diagnostics affected=row_count;
  if affected<>0 then raise exception 'nonowner deleted comment'; end if;
  begin insert into public.restaurant_votes(restaurant_id,round,user_id,choice) values(r,1,b,'up'); raise exception 'direct vote write allowed'; exception when insufficient_privilege then null; end;
  perform public.cast_restaurant_vote(r,1,'up');
  perform set_config('request.jwt.claim.sub',c::text,true); perform public.cast_restaurant_vote(r,1,'up');
  state:=public.restaurant_discussion(r);
  if (state->>'eligible')::integer<>3 or (state->'votes'->>'up')::integer<>3 or (state->>'rating')::integer<>2 or (state->>'round')::integer<>1 then raise exception 'opinions changed medal or round'; end if;
  update public.restaurants set rating=3 where id=r; get diagnostics affected=row_count;
  if affected<>0 then raise exception 'nonowner changed medal'; end if;
  perform set_config('request.jwt.claim.sub',a::text,true);
  update public.restaurants set memo='메모 수정',rating=2 where id=r;
  if (select count(*) from public.restaurant_votes where restaurant_id=r)<>3 then raise exception 'same medal cleared opinions'; end if;
  update public.restaurants set rating=1 where id=r;
  state:=public.restaurant_discussion(r);
  if (state->>'rating')::integer<>1 or (state->>'round')::integer<>2 or (select count(*) from public.restaurant_votes where restaurant_id=r)<>0 then raise exception 'author medal change did not reset opinions'; end if;
  if not exists(select 1 from public.restaurant_comments where id=comment_id) or not exists(select 1 from public.restaurant_photos where restaurant_id=r) then raise exception 'medal edit deleted comments or photos'; end if;
  begin update public.restaurants set vote_round=999 where id=r; raise exception 'client changed opinion version'; exception when insufficient_privilege then null; end;
  perform set_config('request.jwt.claim.sub',b::text,true);
  begin perform public.cast_restaurant_vote(r,1,'down'); raise exception 'stale vote accepted'; exception when raise_exception then if sqlerrm<>'vote_round_changed' then raise; end if; end;
  perform public.cast_restaurant_vote(r,2,'down');
  perform set_config('request.jwt.claim.sub',c::text,true); perform public.cast_restaurant_vote(r,2,'down');
  perform set_config('request.jwt.claim.sub',d::text,true); perform public.cast_restaurant_vote(r,2,'down');
  state:=public.restaurant_discussion(r);
  if (state->'votes'->>'down')::integer<>3 or (state->>'rating')::integer<>1 then raise exception 'bronze opinions deleted or changed restaurant'; end if;
  perform set_config('request.jwt.claim.sub',a::text,true); update public.restaurants set rating=3 where id=r;
  perform set_config('request.jwt.claim.sub',b::text,true); perform public.cast_restaurant_vote(r,3,'up'); perform public.cast_restaurant_vote(r,3,'keep');
  state:=public.restaurant_discussion(r);
  if (state->'votes'->>'up')::integer<>0 or (state->'votes'->>'keep')::integer<>1 then raise exception 'opinion replacement counted twice'; end if;
  perform set_config('role','postgres',true);
  if not exists(select 1 from public.restaurants where id=other_r and rating=1) or exists(select 1 from private.restaurant_photo_cleanup where restaurant_id=r) then raise exception 'opinions affected another group or queued deletion'; end if;
  insert into public.restaurant_comments(restaurant_id,user_id,body,created_at) select other_r,a,'의견 '||i,now()-i*interval '1 second' from generate_series(1,25)i;
  perform set_config('request.jwt.claim.sub',a::text,true); perform set_config('role','authenticated',true);
  state:=public.restaurant_discussion(other_r);
  result:=public.restaurant_discussion(other_r,(state->'comments'->19->>'created_at')::timestamptz,(state->'comments'->19->>'id')::uuid);
  if jsonb_array_length(state->'comments')<>21 or jsonb_array_length(result->'comments')<>5 then raise exception 'comment pagination failed'; end if;
  perform set_config('request.jwt.claim.sub',outsider::text,true);
  if exists(select 1 from public.restaurant_comments) then raise exception 'outsider read comments'; end if;
  begin perform public.cast_restaurant_vote(other_r,1,'down'); raise exception 'outsider voted'; exception when raise_exception then if sqlerrm<>'restaurant_unavailable' then raise; end if; end;
  perform set_config('role','postgres',true);
end $$;
select 'author medal editing, advisory opinions, reset only on medal change, privacy and record preservation passed' result;
rollback;
